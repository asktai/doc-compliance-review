def main():
    src = open(SRC, encoding="utf-8").read()
    out = src
    missed = []
    for old, new, why in RULES:
        if old not in out:
            missed.append(old.split("\n")[0][:60])
            continue
        out = out.replace(old, new, 1)
    if missed:
        print("以下替换未命中（原文已变，需重核）：")
        for m in missed:
            print("  - " + m)
        return 1
    post = audit(out)
    open(OUT, "w", encoding="utf-8").write(out)
    print("已写出 %s（%d 条替换）" % (OUT, len(RULES)))
    for w in post:
        print("  [W] " + w)
    return 1 if post else 0


def audit(out):
    """派生后自检：专查**替换动作自己制造出来的缺陷**（2026-10-21 质检后补）。

    为什么单独一道：RULES 里每条替换都是"局部正确"的——把项目路径换掉、把不可迁移的
    命令删掉，单看都对。但**删动作会留下空洞**：命令行删了代码块就空了、工具名换掉
    上下文就断了。这类副作用在逐条替换时看不见，只有跑完看整篇才暴露，
    故必须在写盘前再做一次**整篇级**扫描。
    """
    warn = []
    # (1) 空代码块：上一行说"必做/如下/命令"，下一行却是空壳 → 读者无从照做
    lines = out.splitlines()
    open_at = None
    for i, l in enumerate(lines, 1):
        if l.strip().startswith("```"):
            if open_at is None:
                open_at = i
            else:
                if i - open_at == 1:
                    prev = lines[open_at - 2] if open_at >= 2 else ""
                    warn.append("空代码块（行 %d-%d）——上一行：「%s」；"
                                "删命令行时须改为角色称谓＋用法，不得留空" % (open_at, i, prev[:40]))
                open_at = None
    # (2) 残留的项目绑定字样：替换表漏了哪条，这里兜住。
    #     判据**带斜杠才算路径残留**：`CHANGELOG.md`、`README.md` 这类**通用文件名**
    #     在兜底条款里作为"建议名"出现是合法的（如 12.1.1「未设开发日志则以 CHANGELOG.md
    #     兼作」），按裸词匹配会误报；真要抓的是 `dev/CHANGELOG.md` 这种带项目目录的写法。
    leftovers = ("maint/", "dist/", "pack.py", "check.py", "publish.py",
                 "DEVLOG", "doc-compliance-review",
                 "/CHANGELOG", "renumber-clauses", "sync-clause-refs")
    hit = [w for w in leftovers if w in out]
    if hit:
        warn.append("残留项目绑定字样：%s" % "、".join(hit))
    return warn


